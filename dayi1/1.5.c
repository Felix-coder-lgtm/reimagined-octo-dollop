#include<stdio.h>//预处理指令，作用是导入头文件 
int main(void)// 定义主函数 
{
	printf("%c%c%c\n",'B','\102','\x42');//%c表示输出字符，连续输出三个B 
	printf("%c%c%c\n",'b','\142','\x62');//同上，连续输出三个b 
	printf("%c%c%c\n",'9','\t','7');//\t表示水平制表符 
	printf("%c%c%c\n",'m','\t','d');//m和d属于非约定转义定符 
	return 0;//函数执行完毕时返回函数值0 
}//函数结束标志 

